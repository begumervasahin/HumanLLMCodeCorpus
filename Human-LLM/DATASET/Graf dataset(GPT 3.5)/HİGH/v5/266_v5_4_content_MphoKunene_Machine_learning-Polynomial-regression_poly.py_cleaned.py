import numpy as np
import matplotlib.pyplot as plt
from sklearn.linear_model import LinearRegression
from sklearn.preprocessing import PolynomialFeatures
b1 = np.array([[12], [18], [20], [25], [27]])
b2 = np.array([[14], [15], [16], [20], [27]])
b3 = np.array([[12], [20], [45], [47]])
b4 = np.array([[14], [16], [50], [52]])
b5 = LinearRegression()
b5.fit(b1, b2)
b6 = np.linspace(0, 28, 110).reshape(-1, 1)
b7 = b5.predict(b6)
plt.plot(b6, b7, b8 = 'Linear Regression')
b9 = PolynomialFeatures(degree=2)
b10 = b9.fit_transform(b1)
b11 = b9.transform(b3)
b12 = LinearRegression()
b12.fit(b10, b2)
b13 = b9.transform(b6)
b14 = b12.predict(b13)
plt.plot(b6, b14, b15 = 'r', linestyle='--', b8='Quadratic Regression')
plt.scatter(b1, b2, b8 = 'Training Data')
plt.title('Fish Tank Price Regression based on Diameter')
plt.xlabel('Diameter (in inches)')
plt.ylabel('Price (in dollars)')
plt.xlim(0, 30)
plt.ylim(0, 30)
plt.legend()
plt.grid(True)
plt.show()
print("Training data (linear):")
print(b1)
print("Training data (quadratic):")
print(b10)
print("Test data (linear):")
print(b3)
print("Test data (quadratic):")
print(b11)