import glob
b1 = glob.glob('./[0-9].*')
print("Files/Directories starting with a single digit and any extension:", b1)
b2 = glob.glob('*.gif')
print("Files with a .gif extension in the current directory:", b2)
b3 = glob.glob('?.gif')
print("Files with a single character filename and .gif extension:", b3)
b4 = glob.glob('**/*.txt', recursive=True)
print("Text files (.txt) recursively in all subdirectories:", b4)
b5 = glob.glob('./**/', recursive=True)
print("All directories and subdirectories:", b5)