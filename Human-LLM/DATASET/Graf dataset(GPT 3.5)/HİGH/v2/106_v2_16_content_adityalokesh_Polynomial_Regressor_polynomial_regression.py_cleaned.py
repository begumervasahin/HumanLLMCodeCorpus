
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from sklearn.linear_model import LinearRegression
from sklearn.preprocessing import PolynomialFeatures
b1 = pd.read_csv('/home/chrx/Downloads/Machine-Learning-A-Z-New/Machine Learning A-Z New/Part 2 - Regression/Section 6 - Polynomial Regression/Position_Salaries.csv')
b2 = b1['Level'].values.reshape(-1, 1)
b3 = b1['Salary'].values.reshape(-1, 1)
b4 = LinearRegression()
b4.fit(b2, b3)
b5 = b4.predict(b2)
b6 = PolynomialFeatures(degree=8)
b7 = b6.fit_transform(b2)
b8 = LinearRegression()
b8.fit(b7, b3)
b9 = b8.predict(b7)
plt.scatter(b2, b3, b10 = 'red')
plt.plot(b2, b5, b10 = 'blue')
plt.title('Linear Regression Model')
plt.xlabel('Level')
plt.ylabel('Salary')
plt.show()
plt.scatter(b2, b3, b10 = 'red')
plt.plot(b2, b9, b10 = 'blue')
plt.title('Polynomial Regression Model')
plt.xlabel('Level')
plt.ylabel('Salary')
plt.show()
b11 = np.array([6.5]).reshape(1, -1)
b12 = b4.predict(b11)
print("Predicted Salary using Linear Regression:", b12[0][0])
b13 = b6.transform(b11)
b14 = b8.predict(b13)
print("Predicted Salary using Polynomial Regression:", b14[0][0])