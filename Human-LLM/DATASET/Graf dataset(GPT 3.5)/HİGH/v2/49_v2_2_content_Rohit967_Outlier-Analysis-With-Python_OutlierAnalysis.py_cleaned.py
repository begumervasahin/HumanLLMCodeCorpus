import numpy as np
import pandas as pd
from sklearn.model_selection import train_test_split
from sklearn import svm, metrics
from sklearn.ensemble import IsolationForest
from sklearn.neighbors import LocalOutlierFactor
import matplotlib.pyplot as plt
b1 = pd.read_csv('kddcup.names', skiprows=1, header=None, sep=':')
b1 = dict(b1[0])
b1[41] = 'label'
b2 = pd.read_csv('kddcup.data_10_percent', low_memory=False, header=None, names=b1.values())
b3 = b2[(b2['service'] == "http") & (b2["logged_in"] == 1)]
b3['label'].value_counts().plot(b4 = 'bar')
b5 = ["duration", "src_bytes", "dst_bytes", "label"]
b3 = b3[b5]
b3['attack'] = np.where(b3['label'] == "normal.", 1, -1)
b6 = b3['attack']
b3.drop(["label", "attack"], b7 = 1, inplace=True)
train_data, test_data, train_target, b8 = train_test_split(b3, b6, train_size=0.8)
b9 = b6[b6 == -1].shape[0] / b6.shape[0]
print("One Class SVM")
b10 = svm.OneClassSVM(b9=b9, kernel='rbf', gamma=0.00005)
b10.fit(train_data)
b11 = b10.predict(train_data)
print("===================")
print("For Training Data: ")
print("===================")
print("accuracy: ", metrics.accuracy_score(train_target, b11))
print("precision: ", metrics.precision_score(train_target, b11))
print("recall: ", metrics.recall_score(train_target, b11))
print("f1: ", metrics.f1_score(train_target, b11))
b12 = b10.predict(test_data)
print("===============")
print("For Test Data: ")
print("===============")
print("accuracy: ", metrics.accuracy_score(b8, b12))
print("precision: ", metrics.precision_score(b8, b12))
print("recall: ", metrics.recall_score(b8, b12))
print("f1: ", metrics.f1_score(b8, b12))
print("Isolation Forest")
b13 = IsolationForest(contamination=b9, random_state=42)
b13.fit(train_data)
b14 = b13.predict(train_data)
print("===================")
print("For Training Data: ")
print("===================")
print("accuracy: ", metrics.accuracy_score(train_target, b14))
print("precision: ", metrics.precision_score(train_target, b14))
print("recall: ", metrics.recall_score(train_target, b14))
print("f1: ", metrics.f1_score(train_target, b14))
b15 = b13.predict(test_data)
print("===============")
print("For Test Data: ")
print("===============")
print("accuracy: ", metrics.accuracy_score(b8, b15))
print("precision: ", metrics.precision_score(b8, b15))
print("recall: ", metrics.recall_score(b8, b15))
print("f1: ", metrics.f1_score(b8, b15))
print("Local Outlier Factor")
b16 = LocalOutlierFactor(n_neighbors=35, contamination=b9)
b16.fit(train_data)
b17 = b16.fit_predict(train_data)
print("===================")
print("For Training Data: ")
print("===================")
print("accuracy: ", metrics.accuracy_score(train_target, b17))
print("precision: ", metrics.precision_score(train_target, b17))
print("recall: ", metrics.recall_score(train_target, b17))
print("f1: ", metrics.f1_score(train_target, b17))
b18 = b16.fit_predict(test_data)
print("===============")
print("For Test Data: ")
print("===============")
print("accuracy: ", metrics.accuracy_score(b8, b18))
print("precision: ", metrics.precision_score(b8, b18))
print("recall: ", metrics.recall_score(b8, b18))
print("f1: ", metrics.f1_score(b8, b18))
