import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from statsmodels.tsa.stattools import adfuller, acf, pacf
from statsmodels.tsa.arima.b21 import ARIMA
from statsmodels.tsa.b15 import seasonal_decompose
b1 = pd.read_csv('C:/Users/PATH/DataSet/Milano_WeatherPhenomena/mi_meteo_2001.csv', names=['id','Day','value'])
b1['Day'] = pd.to_datetime(b1['Day'], b2 = True)
b1.set_index('Day', b3 = True)
b1 = b1.resample('24H').mean()
plt.xlabel('Date')
plt.ylabel('Degree in Celsius')
plt.plot(b1)
plt.show()
b4 = b1.rolling(window=2).mean()
b5 = b1.rolling(window=2).std()
plt.plot(b1, b6 = 'blue', b17='Original')
plt.plot(b4, b6 = 'red', b17='Rolling Mean')
plt.plot(b5, b6 = 'black', b17='Rolling Std')
plt.legend(b7 = 'best')
plt.title('Rolling Mean & Standard Deviation')
plt.show()
def fonk1(timeseries):
    b4 = timeseries.rolling(window=2).mean()
    b5 = timeseries.rolling(window=2).std()
    plt.plot(timeseries, b6 = 'blue', b17='Original')
    plt.plot(b4, b6 = 'red', b17='Rolling Mean')
    plt.plot(b5, b6 = 'black', b17='Rolling Std')
    plt.legend(b7 = 'best')
    plt.title('Rolling Mean & Standard Deviation')
    plt.show()
    print('Results of Dickey-Fuller Test:')
    b8 = adfuller(timeseries['value'], autolag='AIC')
    b9 = pd.Series(b8[0:4], index=['Test Statistic', 'p-value', 'Lags Used', 'Number of Observations Used'])
    for key, value in b8[4].items():
        b9['Critical Value (%s)' % key] = value
    print(b9)
fonk1(b1)
b10 = np.log(b1)
b11 = b10.rolling(window=2).mean()
b12 = b10 - b11
b12.dropna(b3 = True)
fonk1(b12)
b13 = seasonal_decompose(b10)
b14 = b13.b14
b15 = b13.b15
b16 = b13.resid
plt.subplot(411)
plt.plot(b10, b17 = 'Original')
plt.legend(b7 = 'best')
plt.subplot(412)
plt.plot(b14, b17 = 'Trend')
plt.legend(b7 = 'best')
plt.subplot(413)
plt.plot(b15, b17 = 'Seasonal')
plt.legend(b7 = 'best')
plt.subplot(414)
plt.plot(b16, b17 = 'Residuals')
plt.legend(b7 = 'best')
plt.tight_layout()
plt.show()
b18 = acf(b12, nlags=20)
b19 = pacf(b12, nlags=20, method='ols')
plt.subplot(121)
plt.plot(b18)
plt.axhline(b20 = 0, linestyle='--', b6='gray')
plt.axhline(b20 = -1.96/np.sqrt(len(b12)), linestyle='--', b6='gray')
plt.axhline(b20 = 1.96/np.sqrt(len(b12)), linestyle='--', b6='gray')
plt.title('Autocorrelation Function')
plt.subplot(122)
plt.plot(b19)
plt.axhline(b20 = 0, linestyle='--', b6='gray')
plt.axhline(b20 = -1.96/np.sqrt(len(b12)), linestyle='--', b6='gray')
plt.axhline(b20 = 1.96/np.sqrt(len(b12)), linestyle='--', b6='gray')
plt.title('Partial Autocorrelation Function')
plt.tight_layout()
plt.show()
b21 = ARIMA(b10, order=(2, 1, 2))
b22 = b21.fit(disp=-1)
plt.plot(b12)
plt.plot(b22.fittedvalues, b6 = 'red')
plt.title('RSS: %.4f' % sum((b22.fittedvalues - b12["value"])**2))
plt.show()
b23 = pd.Series(b22.fittedvalues, copy=True)
b24 = b23.cumsum()
b25 = pd.Series(b10['value'].iloc[0], index=b10.index)
b25 = b25.add(b24, fill_value=0)
b26 = np.exp(b25)
plt.plot(b1)
plt.plot(b26)
plt.show()
b27 = b22.b27(steps=1)
print('Forecasted temperature:', np.exp(b27[0]))