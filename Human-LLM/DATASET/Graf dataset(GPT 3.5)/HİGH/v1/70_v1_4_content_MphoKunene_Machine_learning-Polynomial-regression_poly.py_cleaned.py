import numpy as np
import matplotlib.pyplot as plt
from sklearn.linear_model import LinearRegression
from sklearn.preprocessing import PolynomialFeatures
b1 = np.array([[12], [18], [20], [25], [27]])
b2 = np.array([[14], [15], [16], [20], [27]])
b3 = np.array([[12], [20], [45], [47]])
b4 = np.array([[14], [16], [50], [52]])
b5 = LinearRegression()
b5.fit(b1, b2)
b6 = PolynomialFeatures(degree=2)
b7 = b6.fit_transform(b1)
b8 = b6.transform(b3)
b9 = LinearRegression()
b9.fit(b7, b2)
b10 = np.linspace(0, 50, 100)
b11 = b5.predict(b10.reshape(-1, 1))
b12 = b6.transform(b10.reshape(b10.shape[0], 1))
b13 = b9.predict(b12)
plt.figure()
plt.plot(b10, b11, b14 = 'Linear Fit')
plt.plot(b10, b13, b14 = 'Quadratic Fit', linestyle='--')
plt.scatter(b1, b2, b14 = 'Training Data')
plt.scatter(b3, b4, b14 = 'Test Data', color='red')
plt.title('Fish Tank Price Regression')
plt.xlabel('Diameter in inches')
plt.ylabel('Price in dollars')
plt.legend()
plt.grid(True)
plt.axis([0, 50, 0, 60])
plt.show()
print("Training Data:")
print(b1)
print("Quadratic Training Data:")
print(b7)
print("Test Data:")
print(b3)
print("Quadratic Test Data:")
print(b8)