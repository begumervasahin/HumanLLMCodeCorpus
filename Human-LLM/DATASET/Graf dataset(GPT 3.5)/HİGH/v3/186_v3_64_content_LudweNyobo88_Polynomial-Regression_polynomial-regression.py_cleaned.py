from sklearn.linear_model import LinearRegression
from sklearn.preprocessing import PolynomialFeatures
def fonk1(b7, b8, model, b14, b6, b12):
    b1 = PolynomialFeatures(b14=b14)
    b2 = b1.fit_transform(b7)
    model.fit(b2, b8)
    b3 = np.linspace(0, 26, 100).reshape(-1, 1)
    b4 = b1.transform(b3)
    b5 = model.predict(b4)
    plt.plot(b3, b5, b6 = b6, linestyle='--', b12=b12)
