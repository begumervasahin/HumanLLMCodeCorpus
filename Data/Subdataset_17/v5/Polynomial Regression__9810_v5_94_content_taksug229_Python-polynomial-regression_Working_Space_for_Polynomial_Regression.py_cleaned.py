import numpy as np
import matplotlib.pyplot as plt
import pandas as pd
from sklearn.linear_model import LinearRegression
from sklearn.preprocessing import PolynomialFeatures
dataset = pd.read_csv('Position_Salaries.csv')
X = dataset.iloc[:, 1:2].values
y = dataset.iloc[:, 2].values
linear_regressor = LinearRegression()
linear_regressor.fit(X, y)
poly_features = PolynomialFeatures(degree=4)
X_poly = poly_features.fit_transform(X)
poly_regressor = LinearRegression()
poly_regressor.fit(X_poly, y)
plt.figure(figsize=(10, 6))
plt.scatter(X, y, color='red', label='Actual Salary')
plt.plot(X, linear_regressor.predict(X), color='blue', label='Linear Regression')
plt.title('Linear Regression: Position vs Salary')
plt.xlabel('Position Level')
plt.ylabel('Salary')
plt.legend()
plt.grid(True)
plt.show()
plt.figure(figsize=(10, 6))
plt.scatter(X, y, color='red', label='Actual Salary')
plt.plot(X, poly_regressor.predict(poly_features.fit_transform(X)), color='blue', label='Polynomial Regression')
plt.title('Polynomial Regression: Position vs Salary')
plt.xlabel('Position Level')
plt.ylabel('Salary')
plt.legend()
plt.grid(True)
plt.show()
X_grid = np.arange(min(X), max(X), 0.1).reshape(-1, 1)
plt.figure(figsize=(10, 6))
plt.scatter(X, y, color='red', label='Actual Salary')
plt.plot(X_grid, poly_regressor.predict(poly_features.fit_transform(X_grid)), color='blue', label='Polynomial Regression')
plt.title('Polynomial Regression with Higher Resolution')
plt.xlabel('Position Level')
plt.ylabel('Salary')
plt.legend()
plt.grid(True)
plt.show()
position_level = 6.5
linear_prediction = linear_regressor.predict([[position_level]])
polynomial_prediction = poly_regressor.predict(poly_features.fit_transform([[position_level]]))
print(f"Linear Regression Prediction for position level {position_level}: {linear_prediction[0]}")
print(f"Polynomial Regression Prediction for position level {position_level}: {polynomial_prediction[0]}")