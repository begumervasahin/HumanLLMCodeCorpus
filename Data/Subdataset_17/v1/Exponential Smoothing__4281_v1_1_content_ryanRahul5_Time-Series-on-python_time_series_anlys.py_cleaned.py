def fit_arima_model(ts_log, order):
    model = ARIMA(ts_log, order=order)
    results = model.fit(disp=-1)
    plt.figure()
    plt.plot(ts_log_diff)
    plt.plot(results.fittedvalues, color='red')
    plt.title(f'RSS: {sum((results.fittedvalues-ts_log_diff)**2):.4f}')
    plt.show()
    return results
