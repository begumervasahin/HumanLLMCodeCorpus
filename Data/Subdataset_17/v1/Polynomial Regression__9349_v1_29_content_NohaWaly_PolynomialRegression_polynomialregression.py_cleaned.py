import matplotlib.pyplot as plt
import pandas as pd
import numpy as np
from sklearn.preprocessing import PolynomialFeatures
from sklearn import linear_model
from sklearn.metrics import r2_score
df = pd.read_csv("FuelConsumption.csv")
cdf = df[['ENGINESIZE', 'CYLINDERS', 'FUELCONSUMPTION_COMB', 'CO2EMISSIONS']]
plt.scatter(cdf.ENGINESIZE, cdf.CO2EMISSIONS, color='blue')
plt.xlabel("Engine size")
plt.ylabel("Emission")
plt.show()
msk = np.random.rand(len(df)) < 0.8
train = cdf[msk]
test = cdf[~msk]
train_x = np.asanyarray(train[['ENGINESIZE']])
train_y = np.asanyarray(train[['CO2EMISSIONS']])
test_x = np.asanyarray(test[['ENGINESIZE']])
test_y = np.asanyarray(test[['CO2EMISSIONS']])
poly2 = PolynomialFeatures(degree=2)
train_x_poly2 = poly2.fit_transform(train_x)
clf2 = linear_model.LinearRegression()
clf2.fit(train_x_poly2, train_y)
print('Degree 2 Polynomial Regression:')
print('Coefficients: ', clf2.coef_)
print('Intercept: ', clf2.intercept_)
plt.scatter(train.ENGINESIZE, train.CO2EMISSIONS, color='blue')
XX = np.arange(0.0, 10.0, 0.1)
yy = clf2.intercept_[0] + clf2.coef_[0][1] * XX + clf2.coef_[0][2] * np.power(XX, 2)
plt.plot(XX, yy, '-r')
plt.xlabel("Engine size")
plt.ylabel("Emission")
plt.show()
test_x_poly2 = poly2.transform(test_x)
test_y2_pred = clf2.predict(test_x_poly2)
print("Mean absolute error: %.2f" % np.mean(np.absolute(test_y2_pred - test_y)))
print("Residual sum of squares (MSE): %.2f" % np.mean((test_y2_pred - test_y) ** 2))
print("R2-score: %.2f" % r2_score(test_y2_pred, test_y))
poly3 = PolynomialFeatures(degree=3)
train_x_poly3 = poly3.fit_transform(train_x)
clf3 = linear_model.LinearRegression()
clf3.fit(train_x_poly3, train_y)
print('Degree 3 Polynomial Regression:')
print('Coefficients: ', clf3.coef_)
print('Intercept: ', clf3.intercept_)
plt.scatter(train.ENGINESIZE, train.CO2EMISSIONS, color='blue')
yy = clf3.intercept_[0] + clf3.coef_[0][1] * XX + clf3.coef_[0][2] * np.power(XX, 2) + clf3.coef_[0][3] * np.power(XX, 3)
plt.plot(XX, yy, '-r')
plt.xlabel("Engine size")
plt.ylabel("Emission")
plt.show()
test_x_poly3 = poly3.transform(test_x)
test_y3_pred = clf3.predict(test_x_poly3)
print("Mean absolute error: %.2f" % np.mean(np.absolute(test_y3_pred - test_y)))
print("Residual sum of squares (MSE): %.2f" % np.mean((test_y3_pred - test_y) ** 2))
print("R2-score: %.2f" % r2_score(test_y3_pred, test_y))