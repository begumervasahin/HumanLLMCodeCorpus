import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.preprocessing import PolynomialFeatures
from sklearn.feature_selection import f_regression, mutual_info_regression
from sklearn.model_selection import train_test_split
from sklearn.linear_model import LinearRegression
from sklearn import metrics
customers = pd.read_csv("Ecommerce Customers")
print(customers.head())
print(customers.describe())
sns.set_palette("GnBu_d")
sns.set_style('whitegrid')
sns.jointplot(x='Time on Website', y='Yearly Amount Spent', data=customers)
sns.jointplot(x='Time on App', y='Yearly Amount Spent', data=customers)
sns.jointplot(x='Time on App', y='Length of Membership', kind='hex', data=customers)
sns.pairplot(customers)
sns.lmplot(x='Length of Membership', y='Yearly Amount Spent', data=customers)
y = customers['Yearly Amount Spent']
X = customers[['Avg. Session Length', 'Time on App', 'Time on Website', 'Length of Membership']]
poly = PolynomialFeatures(degree=2, interaction_only=False, include_bias=True)
X_poly = poly.fit_transform(X)
print(f_regression(X, y, center=True))
print(mutual_info_regression(X, y, discrete_features='auto', n_neighbors=3, copy=True, random_state=None))
X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.3, random_state=101)
X1 = X.drop('Time on App', axis=1)
X1_train, X1_test, y_train, y_test = train_test_split(X1, y, test_size=0.3, random_state=101)
X2_train, X2_test, y_train, y_test = train_test_split(X_poly, y, test_size=0.3, random_state=101)
lm = LinearRegression()
lm1 = LinearRegression()
lm2 = LinearRegression()
lm.fit(X_train, y_train)
lm1.fit(X1_train, y_train)
lm2.fit(X2_train, y_train)
print('Model 1 Coefficients:', lm.coef_)
print('Model 2 Coefficients:', lm1.coef_)
print('Model 3 Coefficients:', lm2.coef_)
predictions = lm.predict(X_test)
predictions1 = lm1.predict(X1_test)
predictions2 = lm2.predict(X2_test)
plt.scatter(y_test, predictions)
plt.xlabel('Y Test')
plt.ylabel('Predicted Y')
plt.title('Model 1 Predictions')
plt.show()
plt.scatter(y_test, predictions1)
plt.xlabel('Y Test')
plt.ylabel('Predicted Y')
plt.title('Model 2 Predictions')
plt.show()
plt.scatter(y_test, predictions2)
plt.xlabel('Y Test')
plt.ylabel('Predicted Y')
plt.title('Model 3 Predictions')
plt.show()
def evaluate_model(y_test, predictions, model_name):
    print(f'{model_name}')
    print('MAE:', metrics.mean_absolute_error(y_test, predictions))
    print('MSE:', metrics.mean_squared_error(y_test, predictions))
    print('RMSE:', np.sqrt(metrics.mean_squared_error(y_test, predictions)))
    print()
evaluate_model(y_test, predictions, 'Model 1')
evaluate_model(y_test, predictions1, 'Model 2')
evaluate_model(y_test, predictions2, 'Model 3')