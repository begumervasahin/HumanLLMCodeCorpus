import numpy as np
import matplotlib.pyplot as plt
import pandas as pd
from sklearn.linear_model import LinearRegression
from sklearn.preprocessing import PolynomialFeatures
dataset = pd.read_csv('Position_Salaries.csv')
X = dataset.iloc[:, 1:2].values
y = dataset.iloc[:, 2].values
linear_regressor = LinearRegression()
linear_regressor.fit(X, y)
polynomial_features = PolynomialFeatures(degree=4)
X_poly = polynomial_features.fit_transform(X)
polynomial_regressor = LinearRegression()
polynomial_regressor.fit(X_poly, y)
plt.figure(figsize=(12, 6))
plt.subplot(1, 2, 1)
plt.scatter(X, y, color='red')
plt.plot(X, linear_regressor.predict(X), color='blue')
plt.title('Linear Regression')
plt.xlabel('Position Level')
plt.ylabel('Salary')
plt.subplot(1, 2, 2)
plt.scatter(X, y, color='red')
plt.plot(X, polynomial_regressor.predict(X_poly), color='blue')
plt.title('Polynomial Regression')
plt.xlabel('Position Level')
plt.ylabel('Salary')
plt.tight_layout()
plt.show()
X_grid = np.arange(min(X), max(X), 0.1)
X_grid = X_grid.reshape((len(X_grid), 1))
plt.scatter(X, y, color='red')
plt.plot(X_grid, polynomial_regressor.predict(polynomial_features.transform(X_grid)), color='blue')
plt.title('Polynomial Regression (Smoother Curve)')
plt.xlabel('Position Level')
plt.ylabel('Salary')
plt.show()
linear_prediction = linear_regressor.predict([[6.5]])
print(f"Linear Regression Prediction for position level 6.5: {linear_prediction[0]}")
polynomial_prediction = polynomial_regressor.predict(polynomial_features.transform([[6.5]]))
print(f"Polynomial Regression Prediction for position level 6.5: {polynomial_prediction[0]}")