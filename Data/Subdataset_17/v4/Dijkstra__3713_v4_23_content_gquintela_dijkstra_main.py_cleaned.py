from dijkstra import Graph, get_dijkstra_path
def create_graphs():
    graph1 = Graph()
    graph1.add_directed_edge('a', 'b', 4)
    graph1.add_directed_edge('a', 'h', 8)
    graph1.add_directed_edge('b', 'c', 8)
    graph1.add_directed_edge('c', 'd', 7)
    graph1.add_directed_edge('b', 'h', 11)
    graph1.add_directed_edge('h', 'i', 7)
    graph1.add_directed_edge('i', 'c', 2)
    graph1.add_directed_edge('i', 'g', 6)
    graph1.add_directed_edge('h', 'g', 1)
    graph1.add_directed_edge('g', 'f', 2)
    graph1.add_directed_edge('c', 'f', 4)
    graph1.add_directed_edge('d', 'f', 14)
    graph1.add_directed_edge('d', 'e', 9)
    graph1.add_directed_edge('f', 'e', 10)
    graph2 = Graph()
    graph2.add_undirected_edge('s', 't', 10)
    graph2.add_undirected_edge('s', 'y', 5)
    graph2.add_undirected_edge('t', 'x', 1)
    graph2.add_undirected_edge('y', 'z', 2)
    graph2.add_undirected_edge('t', 'y', 2)
    graph2.add_undirected_edge('y', 't', 3)
    graph2.add_undirected_edge('x', 'z', 4)
    graph2.add_undirected_edge('z', 'x', 6)
    graph2.add_undirected_edge('y', 'x', 9)
    graph2.add_undirected_edge('z', 's', 7)
    return graph1, graph2
def main():
    graph1, graph2 = create_graphs()
    path = get_dijkstra_path(graph2, 't', 's')
    print(f"The shortest path from 't' to 's' is: {path}")
if __name__ == "__main__":
    main()