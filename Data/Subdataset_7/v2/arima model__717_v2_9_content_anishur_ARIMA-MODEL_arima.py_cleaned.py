import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from statsmodels.tsa.stattools import adfuller, acf, pacf
from statsmodels.tsa.arima.b22 import ARIMA
from statsmodels.tsa.b16 import seasonal_decompose
b1 = 'C:/Users/PATH/DataSet/Milano_WeatherPhenomena/mi_meteo_2001.csv'
b2 = pd.read_csv(b1, names=['id', 'Day', 'value'])
b2['Day'] = pd.to_datetime(b2['Day'], b3 = True)
b2.set_index('Day', b4 = True)
b2 = b2.resample('24H').mean()
plt.xlabel('Date')
plt.ylabel('Temperature (Celsius)')
plt.plot(b2)
plt.show()
b5 = b2.rolling(window=2).mean()
b6 = b2.rolling(window=2).std()
plt.plot(b2, b7 = 'blue', b18='Original')
plt.plot(b5, b7 = 'red', b18='Rolling Mean')
plt.plot(b6, b7 = 'black', b18='Rolling Std')
plt.legend(b8 = 'best')
plt.title('Rolling Mean & Standard Deviation')
plt.show()
def fonk1(timeseries):
    b5 = timeseries.rolling(window=2).mean()
    b6 = timeseries.rolling(window=2).std()
    plt.plot(timeseries, b7 = 'blue', b18='Original')
    plt.plot(b5, b7 = 'red', b18='Rolling Mean')
    plt.plot(b6, b7 = 'black', b18='Rolling Std')
    plt.legend(b8 = 'best')
    plt.title('Rolling Mean & Standard Deviation')
    plt.show()
    print('Results of Dickey-Fuller Test:')
    b9 = adfuller(timeseries['value'], autolag='AIC')
    b10 = pd.Series(b9[0:4], index=['Test Statistic', 'p-value', 'Lags Used', 'Observations Used'])
    for key, value in b9[4].items():
        b10['Critical Value (%s)' % key] = value
    print(b10)
fonk1(b2)
b11 = np.log(b2)
b12 = b11.rolling(window=2).mean()
b13 = b11 - b12
b13.dropna(b4 = True)
fonk1(b13)
b14 = seasonal_decompose(b11)
b15 = b14.b15
b16 = b14.b16
b17 = b14.resid
plt.subplot(411)
plt.plot(b11, b18 = 'Original')
plt.legend(b8 = 'best')
plt.subplot(412)
plt.plot(b15, b18 = 'Trend')
plt.legend(b8 = 'best')
plt.subplot(413)
plt.plot(b16, b18 = 'Seasonal')
plt.legend(b8 = 'best')
plt.subplot(414)
plt.plot(b17, b18 = 'Residuals')
plt.legend(b8 = 'best')
plt.tight_layout()
plt.show()
b19 = acf(b13, nlags=20)
b20 = pacf(b13, nlags=20, method='ols')
plt.subplot(121)
plt.plot(b19)
plt.axhline(b21 = 0, linestyle='--', b7='gray')
plt.axhline(b21 = -1.96/np.sqrt(len(b13)), linestyle='--', b7='gray')
plt.axhline(b21 = 1.96/np.sqrt(len(b13)), linestyle='--', b7='gray')
plt.title('Autocorrelation Function')
plt.subplot(122)
plt.plot(b20)
plt.axhline(b21 = 0, linestyle='--', b7='gray')
plt.axhline(b21 = -1.96/np.sqrt(len(b13)), linestyle='--', b7='gray')
plt.axhline(b21 = 1.96/np.sqrt(len(b13)), linestyle='--', b7='gray')
plt.title('Partial Autocorrelation Function')
plt.tight_layout()
plt.show()
b22 = ARIMA(b11, order=(2, 1, 2))
b23 = b22.fit(disp=-1)
plt.plot(b13)
plt.plot(b23.fittedvalues, b7 = 'red')
plt.title('RSS: %.4f' % sum((b23.fittedvalues - b13["value"])**2))
plt.show()
b24 = pd.Series(b23.fittedvalues, copy=True)
b25 = b24.cumsum()
b26 = pd.Series(b11['value'].iloc[0], index=b11.index)
b26 = b26.add(b25, fill_value=0)
b27 = np.exp(b26)
plt.plot(b2)
plt.plot(b27)
plt.show()
b28 = b23.b28(steps=1)
print('Forecasted temperature:', np.exp(b28[0]))