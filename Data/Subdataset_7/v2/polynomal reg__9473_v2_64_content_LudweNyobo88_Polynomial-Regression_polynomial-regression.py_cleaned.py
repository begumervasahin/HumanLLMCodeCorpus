import numpy as np
import matplotlib.pyplot as plt
from sklearn.linear_model import LinearRegression
from sklearn.preprocessing import PolynomialFeatures
b1 = np.array([[6], [8], [10], [14], [18]])
b2 = np.array([[7], [9], [13], [17.5], [18]])
b3 = np.array([[6], [8], [11], [16]])
b4 = np.array([[8], [12], [15], [18]])
b5 = LinearRegression()
b5.fit(b1, b2)
b6 = np.linspace(0, 26, 100)
b7 = b5.predict(b6.reshape(-1, 1))
plt.plot(b6, b7)
b8 = PolynomialFeatures(degree=2)
b9 = b8.fit_transform(b1)
b10 = b8.transform(b3)
b11 = LinearRegression()
b11.fit(b9, b2)
b12 = b8.transform(b6.reshape(-1, 1))
b13 = b11.predict(b12)
plt.plot(b6, b13, b14 = 'r', linestyle='--')
plt.scatter(b1, b2)
plt.title('Pizza price regressed on diameter')
plt.xlabel('Diameter in inches')
plt.ylabel('Price in dollars')
plt.axis([0, 25, 0, 25])
plt.grid(True)
plt.legend(['Linear Regression', 'Quadratic Regression', 'Training Data'])
plt.show()
print("Training Data:")
print("b1:")
print(b1)
