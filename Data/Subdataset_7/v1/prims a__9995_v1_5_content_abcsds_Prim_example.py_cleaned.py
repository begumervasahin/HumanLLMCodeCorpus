import matplotlib.pyplot as plt
import networkx as nx
from prim import prim
b1 = nx.Graph()
b1.add_edge('A', 'B', b2 = 3)
b1.add_edge('A', 'D', b2 = 5)
b1.add_edge('A', 'E', b2 = 9)
b1.add_edge('B', 'C', b2 = 5)
b1.add_edge('B', 'D', b2 = 4)
b1.add_edge('B', 'E', b2 = 8)
b1.add_edge('C', 'D', b2 = 7)
b1.add_edge('C', 'b1', b2 = 3)
b1.add_edge('D', 'F', b2 = 8)
b1.add_edge('D', 'b1', b2 = 5)
b1.add_edge('D', 'H', b2 = 6)
b1.add_edge('E', 'F', b2 = 2)
b1.add_edge('F', 'H', b2 = 10)
b1.add_edge('b1', 'I', b2 = 1)
b1.add_edge('H', 'I', b2 = 3)
b3 = prim(b1, 'A')
b4 = [n for n in b1.edges() if n not in b3]
print("Minimal Spanning Tree:", b3)
b5 = nx.spring_layout(b1)
nx.draw_networkx_nodes(b1, b5, b6 = 500)
nx.draw_networkx_edges(b1, b5, b7 = b3, width=6)
nx.draw_networkx_edges(b1, b5, b7 = b4, width=6, alpha=0.5, edge_color='b', style='dashed')
nx.draw_networkx_labels(b1, b5, b8 = 20, font_family='sans-serif')
plt.axis('off')
plt.show()