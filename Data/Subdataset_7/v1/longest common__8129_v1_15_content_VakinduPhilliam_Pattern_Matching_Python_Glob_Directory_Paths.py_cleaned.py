import glob
b1 = glob.glob('./[0-9].*')
print("Files starting with a digit:", b1)
b2 = glob.glob('*.gif')
print("GIF files:", b2)
b3 = glob.glob('?.gif')
print("Single character GIF files:", b3)
b4 = glob.glob('**/*.txt', recursive=True)
print("Text files (recursive):", b4)
b5 = glob.glob('./**/', recursive=True)
print("Directories (recursive):", b5)