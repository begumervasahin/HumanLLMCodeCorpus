import numpy as np
import matplotlib.pyplot as plt
import pandas as pd
from statsmodels.tsa.stattools import adfuller
from statsmodels.tsa.arima_model import ARIMA
from statsmodels.tsa.b21 import seasonal_decompose
from statsmodels.tsa.stattools import acf, pacf
b1 = pd.read_csv('annual.csv', parse_dates=['YEAR'])
b1['YEAR'] = pd.date_range(b2 = '1901', end='2017', freq='AS')
b3 = b1.set_index(['YEAR'])
plt.xlabel("Date")
plt.ylabel("Rainfall")
plt.plot(b3)
b4 = b3.rolling(window=1).b7()
b5 = b3.rolling(window=1).b8()
b6 = plt.plot(b3, b16='blue', b23='Original')
b7 = plt.plot(b4, b16='red', b23='Rolling Mean')
b8 = plt.plot(b5, b16='black', b23='Rolling Std')
plt.legend(b9 = 'best')
plt.title('Rolling b7 vs Standard deviation')
plt.show(b10 = False)
print('Results of Dickey-Fuller Test:')
b11 = adfuller(b3['ANNUAL'], autolag='AIC')
b12 = pd.Series(b11[0:4], index=['Test Statistics', 'p-value'])
for key, value in b11[4].items():
    b12['Critical value (%s)' % key] = value
print(b12)
b13 = np.log(b3)
b14 = b13.rolling(window=1).b7()
b15 = b13.rolling(window=1).b8()
plt.plot(b13)
plt.plot(b14, b16 = 'red')
b17 = b13 - b13.shift()
b17.dropna(b18 = True)
plt.plot(b17)
b19 = seasonal_decompose(b13)
b20 = b19.b20
b21 = b19.b21
b22 = b19.resid
plt.subplot(411)
plt.plot(b13, b23 = 'Original')
plt.legend(b9 = 'best')
plt.subplot(412)
plt.plot(b20, b23 = 'Trend')
plt.legend(b9 = 'best')
plt.subplot(413)
plt.plot(b21, b23 = 'Seasonality')
plt.legend(b9 = 'best')
plt.subplot(414)
plt.plot(b22, b23 = 'Residual')
plt.legend(b9 = 'best')
plt.tight_layout()
b24 = acf(b17, nlags=20)
b25 = pacf(b17, nlags=20, method='ols')
plt.subplot(121)
plt.plot(b24)
plt.axhline(b26 = 0, linestyle='--', b16='gray')
plt.axhline(b26 = -1.96 / np.sqrt(len(b17)), linestyle='--', b16='gray')
plt.axhline(b26 = 1.96 / np.sqrt(len(b17)), linestyle='--', b16='gray')
plt.title('Autocorrelation Function')
plt.subplot(122)
plt.plot(b25)
plt.axhline(b26 = 0, linestyle='--', b16='gray')
plt.axhline(b26 = -1.96 / np.sqrt(len(b17)), linestyle='--', b16='gray')
plt.axhline(b26 = 1.96 / np.sqrt(len(b17)), linestyle='--', b16='gray')
plt.title('Partial Autocorrelation Function')
plt.tight_layout()
b27 = ARIMA(b13, order=(1, 1, 1))
b28 = b27.fit(disp=-1)
plt.plot(b17)
plt.plot(b28.fittedvalues, b16 = 'red')
plt.title('RSS: %.4f' % sum((b28.fittedvalues - b17['ANNUAL']) ** 2))
b29 = b28.forecast(steps=90)