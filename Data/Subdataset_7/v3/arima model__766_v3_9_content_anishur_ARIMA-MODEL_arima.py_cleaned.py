import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from statsmodels.tsa.stattools import adfuller, acf, pacf
from statsmodels.tsa.arima.b23 import ARIMA
from statsmodels.tsa.b17 import seasonal_decompose
b1 = 'C:/Users/PATH/DataSet/Milano_WeatherPhenomena/mi_meteo_2001.csv'
b2 = pd.read_csv(b1, names=['id', 'Day', 'Temperature'])
b2['Day'] = pd.to_datetime(b2['Day'], b3 = True)
b2.set_index('Day', b4 = True)
b5 = b2.resample('24H').mean()
plt.xlabel('Date')
plt.ylabel('Temperature (Celsius)')
plt.plot(b5)
plt.show()
b6 = b5.rolling(window=2).mean()
b7 = b5.rolling(window=2).std()
plt.plot(b5, b8 = 'blue', b19='Original')
plt.plot(b6, b8 = 'red', b19='Rolling Mean')
plt.plot(b7, b8 = 'black', b19='Rolling Std')
plt.legend(b9 = 'best')
plt.title('Rolling Mean & Standard Deviation')
plt.show()
def fonk1(timeseries):
    b6 = timeseries.rolling(window=2).mean()
    b7 = timeseries.rolling(window=2).std()
    plt.plot(timeseries, b8 = 'blue', b19='Original')
    plt.plot(b6, b8 = 'red', b19='Rolling Mean')
    plt.plot(b7, b8 = 'black', b19='Rolling Std')
    plt.legend(b9 = 'best')
    plt.title('Rolling Mean & Standard Deviation')
    plt.show()
    print('Results of Dickey-Fuller Test:')
    b10 = adfuller(timeseries['Temperature'], autolag='AIC')
    b11 = pd.Series(b10[0:4], index=['Test Statistic', 'p-value', 'Lags Used', 'Observations Used'])
    for key, value in b10[4].items():
        b11['Critical Value (%s)' % key] = value
    print(b11)
fonk1(b5)
b12 = np.log(b5)
b13 = b12.rolling(window=2).mean()
b14 = b12 - b13
b14.dropna(b4 = True)
fonk1(b14)
b15 = seasonal_decompose(b12)
b16 = b15.b16
b17 = b15.b17
b18 = b15.resid
plt.subplot(411)
plt.plot(b12, b19 = 'Original')
plt.legend(b9 = 'best')
plt.subplot(412)
plt.plot(b16, b19 = 'Trend')
plt.legend(b9 = 'best')
plt.subplot(413)
plt.plot(b17, b19 = 'Seasonal')
plt.legend(b9 = 'best')
plt.subplot(414)
plt.plot(b18, b19 = 'Residuals')
plt.legend(b9 = 'best')
plt.tight_layout()
plt.show()
b20 = acf(b14, nlags=20)
b21 = pacf(b14, nlags=20, method='ols')
plt.subplot(121)
plt.plot(b20)
plt.axhline(b22 = 0, linestyle='--', b8='gray')
plt.axhline(b22 = -1.96/np.sqrt(len(b14)), linestyle='--', b8='gray')
plt.axhline(b22 = 1.96/np.sqrt(len(b14)), linestyle='--', b8='gray')
plt.title('Autocorrelation Function')
plt.subplot(122)
plt.plot(b21)
plt.axhline(b22 = 0, linestyle='--', b8='gray')
plt.axhline(b22 = -1.96/np.sqrt(len(b14)), linestyle='--', b8='gray')
plt.axhline(b22 = 1.96/np.sqrt(len(b14)), linestyle='--', b8='gray')
plt.title('Partial Autocorrelation Function')
plt.tight_layout()
plt.show()
b23 = ARIMA(b12, order=(2, 1, 2))
b24 = b23.fit(disp=-1)
plt.plot(b14)
plt.plot(b24.fittedvalues, b8 = 'red')
plt.title('RSS: %.4f' % sum((b24.fittedvalues - b14["Temperature"])**2))
plt.show()
b25 = pd.Series(b24.fittedvalues, copy=True)
b26 = b25.cumsum()
b27 = pd.Series(b12['Temperature'].iloc[0], index=b12.index)
b27 = b27.add(b26, fill_value=0)
b28 = np.exp(b27)
plt.plot(b5)
plt.plot(b28)
