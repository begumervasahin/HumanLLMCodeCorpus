import numpy as np
import matplotlib.pyplot as plt
from sklearn.linear_model import LinearRegression
from sklearn.preprocessing import PolynomialFeatures
b1 = np.array([6, 8, 10, 14, 18]).reshape(-1, 1)
b2 = np.array([7, 9, 13, 17.5, 18]).reshape(-1, 1)
b3 = np.array([6, 8, 11, 16]).reshape(-1, 1)
b4 = np.array([8, 12, 15, 18]).reshape(-1, 1)
b5 = LinearRegression()
b5.fit(b1, b2)
b6 = np.linspace(0, 26, 100).reshape(-1, 1)
b7 = b5.predict(b6)
plt.plot(b6, b7, b8 = 'Linear Regression')
b9 = PolynomialFeatures(degree=2)
b10 = b9.fit_transform(b1)
b11 = b9.transform(b3)
b12 = LinearRegression()
b12.fit(b10, b2)
b13 = b12.predict(b9.transform(b6))
plt.plot(b6, b13, '--', b14 = 'red', b8='Quadratic Regression')
plt.title('Pizza price regressed on diameter')
plt.xlabel('Diameter in inches')
plt.ylabel('Price in dollars')
plt.legend()
plt.grid(True)
plt.scatter(b1, b2, b8 = 'Training Data')
plt.show()
print("Transformed training data with quadratic features:")
print(b10)
print("\nTransformed testing data with quadratic features:")
print(b11)