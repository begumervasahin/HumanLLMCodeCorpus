import numpy as np
import matplotlib.pyplot as plt
x, b1 = np.loadtxt('dataset.csv', delimiter=',', unpack=True)
b2 = np.polyfit(x, b1, 15)
b3 = np.poly1d(b2)
b4 = np.abs(b1 - b3(x))
b5 = np.unique(x)
b6 = np.array([[value, np.mean(b4[x == value])] for value in b5])
fig, (ax1, ax2) = plt.subplots(2, 1, b7 = (18, 9))
b8 = np.where(b1 > b3(x), 'r', 'b')
ax1.scatter(x, b1, b9 = 2, marker='o', c=b8)
ax1.plot(x, b3(x), 'k', b10 = 1)
ax1.set_title("Value Classifier")
b11 = np.where(b4 > b6[:, 1][np.searchsorted(b5, x)], 'r', 'b')
ax2.scatter(x, b1, b9 = 2, marker='o', c=b11)
ax2.plot(x, b3(x), 'k', b10 = 1)
ax2.set_title("Average Distance Classifier")
plt.tight_layout()
plt.show()