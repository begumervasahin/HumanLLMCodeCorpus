from ECDHE_RSA import ECDHE_RSA
b1 = ECDHE_RSA("b1")
b2 = ECDHE_RSA("b2")
matin_rsa_private, matin_rsa_public, b3 = b1.rsakeygenarate()
mohamad_rsa_private, mohamad_rsa_public, b4 = b2.rsakeygenarate()
matin_ec_private, b5 = b1.gen_ECkeypair()
mohamad_ec_private, b6 = b2.gen_ECkeypair()
print("\n\nmatin private EC key:")
print(matin_ec_private, b5)
print("\nmohamad private EC key:")
print(mohamad_ec_private, b6)
b7 = b1.hash_info(str(b5[0]), str(b5[1]))
b8 = b1.ras_sign(b7, matin_rsa_private, b3)
b9 = b2.hash_info(str(b6[0]), str(b6[1]))
b10 = b2.ras_sign(b9, mohamad_rsa_private, b4)
b11 = b1.hash_info(str(b6[0]), str(b6[1]))
b12 = b1.rsa_verification(b10, mohamad_rsa_public, b4, b11)
print("\n\nmatin verify rsa_sign:")
print(b12)
b13 = b2.hash_info(str(b5[0]), str(b5[1]))
b14 = b2.rsa_verification(b8, matin_rsa_public, b3, b13)
print("\nmohamad verify rsa_sign:")
print(b14)
b15 = b1.gen_ECkeyAg(b6, matin_ec_private)
b16 = b2.gen_ECkeyAg(b5, mohamad_ec_private)
print("\n\nmatin share key:")
print(b15)
print("\nmohamad share key:")
print(b16)
print("\n\ncheck point in curve ?")
print(b1.in_Curve(b15[0], b15[1]))