def area_of_sector():
    aos_window = tk.Tk()
    aos_window.title('Compute Area Of Sector')
    aos_window.geometry("400x400")
    aos_window.configure(background="yellow")
    radius_value = tk.StringVar()
    angle_value = tk.StringVar()
    tk.Label(aos_window, text="Please Enter Radius Here", bg='yellow', font=('Arial',20,'bold')).pack()
    entry1 = tk.Entry(aos_window, textvariable=radius_value, font=('Arial',20,'bold'))
    entry1.pack()
    tk.Label(aos_window, text="Please Enter Angle Here", bg='yellow', font=('Arial',20,'bold')).pack()
    entry2 = tk.Entry(aos_window, textvariable=angle_value, font=('Arial',20,'bold'))
    entry2.pack()
    def compute_area_of_sector():
        radius = float(radius_value.get())
        angle = float(angle_value.get())
        area = (1/2) * radius**2 * angle
        result_label.config(text=f"Area of Sector: {area}")
    btn = tk.Button(aos_window, text="Calculate", command=compute_area_of_sector, font=('Arial',20,'bold'))
    btn.pack()
    result_label = tk.Label(aos_window, text="", font=('Arial',20,'bold'))
    result_label.pack()
