def radian_to_degree():
    rd_window = tk.Tk()
    rd_window.title('Radian to Degree')
    rd_window.geometry("500x500")
    rd_window.configure(background='yellow')
    radian_value = tk.StringVar()
    take_input = tk.Entry(rd_window, textvariable=radian_value, font=('Arial', 15, 'bold'))
    take_input.pack()
    def convert_to_degree():
        radian = float(radian_value.get())
        degree = radian * 180 / 3.14
