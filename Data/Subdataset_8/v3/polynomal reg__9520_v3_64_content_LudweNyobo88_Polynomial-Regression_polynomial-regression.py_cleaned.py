import numpy as np
import matplotlib.pyplot as plt
from sklearn.linear_model import LinearRegression
from sklearn.preprocessing import PolynomialFeatures
def plot_regression(X_train, y_train, model, degree, color, label):
    polynomial_features = PolynomialFeatures(degree=degree)
    X_train_poly = polynomial_features.fit_transform(X_train)
    model.fit(X_train_poly, y_train)
    xx = np.linspace(0, 26, 100).reshape(-1, 1)
    xx_poly = polynomial_features.transform(xx)
    yy = model.predict(xx_poly)
    plt.plot(xx, yy, color=color, linestyle='--', label=label)
X_train = np.array([[6], [8], [10], [14], [18]])
y_train = np.array([[7], [9], [13], [17.5], [18]])
x_test = np.array([[6], [8], [11], [16]])
y_test = np.array([[8], [12], [15], [18]])
linear_regressor = LinearRegression()
linear_regressor.fit(X_train, y_train)
plt.plot(X_train, linear_regressor.predict(X_train), label='Linear Regression')
quadratic_regressor = LinearRegression()
plot_regression(X_train, y_train, quadratic_regressor, degree=2, color='r', label='Quadratic Regression')
plt.scatter(X_train, y_train, label='Training Data')
plt.title('Pizza price regressed on diameter')
plt.xlabel('Diameter in inches')
plt.ylabel('Price in dollars')
plt.axis([0, 25, 0, 25])
plt.grid(True)
plt.legend()
plt.show()
