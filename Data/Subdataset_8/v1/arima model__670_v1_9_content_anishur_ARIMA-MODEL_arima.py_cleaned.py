import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from statsmodels.tsa.stattools import adfuller, acf, pacf
from statsmodels.tsa.arima.model import ARIMA
from statsmodels.tsa.seasonal import seasonal_decompose
df = pd.read_csv('C:/Users/PATH/DataSet/Milano_WeatherPhenomena/mi_meteo_2001.csv', names=['id','Day','value'])
df['Day'] = pd.to_datetime(df['Day'], infer_datetime_format=True)
df.set_index('Day', inplace=True)
df = df.resample('24H').mean()
plt.xlabel('Date')
plt.ylabel('Degree in Celsius')
plt.plot(df)
plt.show()
rolmean = df.rolling(window=2).mean()
rolstd = df.rolling(window=2).std()
plt.plot(df, color='blue', label='Original')
plt.plot(rolmean, color='red', label='Rolling Mean')
plt.plot(rolstd, color='black', label='Rolling Std')
plt.legend(loc='best')
plt.title('Rolling Mean & Standard Deviation')
plt.show()
def test_stationarity(timeseries):
    rolmean = timeseries.rolling(window=2).mean()
    rolstd = timeseries.rolling(window=2).std()
    plt.plot(timeseries, color='blue', label='Original')
    plt.plot(rolmean, color='red', label='Rolling Mean')
    plt.plot(rolstd, color='black', label='Rolling Std')
    plt.legend(loc='best')
    plt.title('Rolling Mean & Standard Deviation')
    plt.show()
    print('Results of Dickey-Fuller Test:')
    dftest = adfuller(timeseries['value'], autolag='AIC')
    dfoutput = pd.Series(dftest[0:4], index=['Test Statistic', 'p-value', 'Lags Used', 'Number of Observations Used'])
    for key, value in dftest[4].items():
        dfoutput['Critical Value (%s)' % key] = value
    print(dfoutput)
test_stationarity(df)
df_log = np.log(df)
moving_avg = df_log.rolling(window=2).mean()
df_log_moving_avg_diff = df_log - moving_avg
df_log_moving_avg_diff.dropna(inplace=True)
test_stationarity(df_log_moving_avg_diff)
decomposition = seasonal_decompose(df_log)
trend = decomposition.trend
seasonal = decomposition.seasonal
residual = decomposition.resid
plt.subplot(411)
plt.plot(df_log, label='Original')
plt.legend(loc='best')
plt.subplot(412)
plt.plot(trend, label='Trend')
plt.legend(loc='best')
plt.subplot(413)
plt.plot(seasonal, label='Seasonal')
plt.legend(loc='best')
plt.subplot(414)
plt.plot(residual, label='Residuals')
plt.legend(loc='best')
plt.tight_layout()
plt.show()
lag_acf = acf(df_log_moving_avg_diff, nlags=20)
lag_pacf = pacf(df_log_moving_avg_diff, nlags=20, method='ols')
plt.subplot(121)
plt.plot(lag_acf)
plt.axhline(y=0, linestyle='--', color='gray')
plt.axhline(y=-1.96/np.sqrt(len(df_log_moving_avg_diff)), linestyle='--', color='gray')
plt.axhline(y=1.96/np.sqrt(len(df_log_moving_avg_diff)), linestyle='--', color='gray')
plt.title('Autocorrelation Function')
plt.subplot(122)
plt.plot(lag_pacf)
plt.axhline(y=0, linestyle='--', color='gray')
plt.axhline(y=-1.96/np.sqrt(len(df_log_moving_avg_diff)), linestyle='--', color='gray')
plt.axhline(y=1.96/np.sqrt(len(df_log_moving_avg_diff)), linestyle='--', color='gray')
plt.title('Partial Autocorrelation Function')
plt.tight_layout()
plt.show()
model = ARIMA(df_log, order=(2, 1, 2))
results = model.fit(disp=-1)
plt.plot(df_log_moving_avg_diff)
plt.plot(results.fittedvalues, color='red')
plt.title('RSS: %.4f' % sum((results.fittedvalues - df_log_moving_avg_diff["value"])**2))
plt.show()
predictions_diff = pd.Series(results.fittedvalues, copy=True)
predictions_diff_cumsum = predictions_diff.cumsum()
predictions_log = pd.Series(df_log['value'].iloc[0], index=df_log.index)
predictions_log = predictions_log.add(predictions_diff_cumsum, fill_value=0)
predictions = np.exp(predictions_log)
plt.plot(df)
plt.plot(predictions)
plt.show()
forecast = results.forecast(steps=1)
print('Forecasted temperature:', np.exp(forecast[0]))