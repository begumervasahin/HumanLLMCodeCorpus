import numpy as np
import matplotlib.pyplot as plt
from sklearn.linear_model import LinearRegression
from sklearn.preprocessing import PolynomialFeatures
X_train = np.array([[6], [8], [10], [14], [18]])
y_train = np.array([[7], [9], [13], [17.5], [18]])
x_test = np.array([[6], [8], [11], [16]])
y_test = np.array([[8], [12], [15], [18]])
regressor = LinearRegression()
regressor.fit(X_train, y_train)
xx = np.linspace(0, 26, 100)
yy = regressor.predict(xx.reshape(-1, 1))
plt.plot(xx, yy)
quadratic_featurizer = PolynomialFeatures(degree=2)
X_train_quadratic = quadratic_featurizer.fit_transform(X_train)
X_test_quadratic = quadratic_featurizer.transform(x_test)
regressor_quadratic = LinearRegression()
regressor_quadratic.fit(X_train_quadratic, y_train)
xx_quadratic = quadratic_featurizer.transform(xx.reshape(-1, 1))
plt.plot(xx, regressor_quadratic.predict(xx_quadratic), c='r', linestyle='--')
plt.scatter(X_train, y_train)
plt.title('Pizza price regressed on diameter')
plt.xlabel('Diameter in inches')
plt.ylabel('Price in dollars')
plt.axis([0, 25, 0, 25])
plt.grid(True)
plt.legend(['Linear Regression', 'Quadratic Regression', 'Training Data'])
plt.show()
print("X_train:")
print(X_train)
print("\nX_train_quadratic:")
print(X_train_quadratic)
print("\nX_test:")
print(x_test)
print("\nX_test_quadratic:")
print(X_test_quadratic)