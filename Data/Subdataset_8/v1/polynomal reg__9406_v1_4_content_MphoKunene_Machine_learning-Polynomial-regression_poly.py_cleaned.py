import numpy as np
import matplotlib.pyplot as plt
from sklearn.linear_model import LinearRegression
from sklearn.preprocessing import PolynomialFeatures
x_train = np.array([[12], [18], [20], [25], [27]])
y_train = np.array([[14], [15], [16], [20], [27]])
x_test = np.array([[12], [20], [45], [47]])
y_test = np.array([[14], [16], [50], [52]])
regressor = LinearRegression()
regressor.fit(x_train, y_train)
quadratic_featurizer = PolynomialFeatures(degree=2)
x_train_quadratic = quadratic_featurizer.fit_transform(x_train)
x_test_quadratic = quadratic_featurizer.transform(x_test)
regressor_quadratic = LinearRegression()
regressor_quadratic.fit(x_train_quadratic, y_train)
xx = np.linspace(0, 50, 100)
yy_linear = regressor.predict(xx.reshape(-1, 1))
xx_quadratic = quadratic_featurizer.transform(xx.reshape(xx.shape[0], 1))
yy_quadratic = regressor_quadratic.predict(xx_quadratic)
plt.figure()
plt.plot(xx, yy_linear, label='Linear Fit')
plt.plot(xx, yy_quadratic, label='Quadratic Fit', linestyle='--')
plt.scatter(x_train, y_train, label='Training Data')
plt.scatter(x_test, y_test, label='Test Data', color='red')
plt.title('Fish Tank Price Regression')
plt.xlabel('Diameter in inches')
plt.ylabel('Price in dollars')
plt.legend()
plt.grid(True)
plt.axis([0, 50, 0, 60])
plt.show()
print("Training Data:")
print(x_train)
print("Quadratic Training Data:")
print(x_train_quadratic)
print("Test Data:")
print(x_test)
print("Quadratic Test Data:")
print(x_test_quadratic)