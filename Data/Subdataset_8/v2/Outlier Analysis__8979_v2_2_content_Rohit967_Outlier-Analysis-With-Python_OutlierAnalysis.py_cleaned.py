import numpy as np
import pandas as pd
from sklearn.model_selection import train_test_split
from sklearn import svm, metrics
from sklearn.ensemble import IsolationForest
from sklearn.neighbors import LocalOutlierFactor
import matplotlib.pyplot as plt
data_names = pd.read_csv('kddcup.names', skiprows=1, header=None, sep=':')
data_names = dict(data_names[0])
data_names[41] = 'label'
data = pd.read_csv('kddcup.data_10_percent', low_memory=False, header=None, names=data_names.values())
http_data = data[(data['service'] == "http") & (data["logged_in"] == 1)]
http_data['label'].value_counts().plot(kind='bar')
relevant_features = ["duration", "src_bytes", "dst_bytes", "label"]
http_data = http_data[relevant_features]
http_data['attack'] = np.where(http_data['label'] == "normal.", 1, -1)
target = http_data['attack']
http_data.drop(["label", "attack"], axis=1, inplace=True)
train_data, test_data, train_target, test_target = train_test_split(http_data, target, train_size=0.8)
nu = target[target == -1].shape[0] / target.shape[0]
print("One Class SVM")
model = svm.OneClassSVM(nu=nu, kernel='rbf', gamma=0.00005)
model.fit(train_data)
train_preds = model.predict(train_data)
print("===================")
print("For Training Data: ")
print("===================")
print("accuracy: ", metrics.accuracy_score(train_target, train_preds))
print("precision: ", metrics.precision_score(train_target, train_preds))
print("recall: ", metrics.recall_score(train_target, train_preds))
print("f1: ", metrics.f1_score(train_target, train_preds))
test_preds = model.predict(test_data)
print("===============")
print("For Test Data: ")
print("===============")
print("accuracy: ", metrics.accuracy_score(test_target, test_preds))
print("precision: ", metrics.precision_score(test_target, test_preds))
print("recall: ", metrics.recall_score(test_target, test_preds))
print("f1: ", metrics.f1_score(test_target, test_preds))
print("Isolation Forest")
iso_forest = IsolationForest(contamination=nu, random_state=42)
iso_forest.fit(train_data)
train_preds1 = iso_forest.predict(train_data)
print("===================")
print("For Training Data: ")
print("===================")
print("accuracy: ", metrics.accuracy_score(train_target, train_preds1))
print("precision: ", metrics.precision_score(train_target, train_preds1))
print("recall: ", metrics.recall_score(train_target, train_preds1))
print("f1: ", metrics.f1_score(train_target, train_preds1))
test_preds1 = iso_forest.predict(test_data)
print("===============")
print("For Test Data: ")
print("===============")
print("accuracy: ", metrics.accuracy_score(test_target, test_preds1))
print("precision: ", metrics.precision_score(test_target, test_preds1))
print("recall: ", metrics.recall_score(test_target, test_preds1))
print("f1: ", metrics.f1_score(test_target, test_preds1))
print("Local Outlier Factor")
lof = LocalOutlierFactor(n_neighbors=35, contamination=nu)
lof.fit(train_data)
train_preds2 = lof.fit_predict(train_data)
print("===================")
print("For Training Data: ")
print("===================")
print("accuracy: ", metrics.accuracy_score(train_target, train_preds2))
print("precision: ", metrics.precision_score(train_target, train_preds2))
print("recall: ", metrics.recall_score(train_target, train_preds2))
print("f1: ", metrics.f1_score(train_target, train_preds2))
test_preds2 = lof.fit_predict(test_data)
print("===============")
print("For Test Data: ")
print("===============")
print("accuracy: ", metrics.accuracy_score(test_target, test_preds2))
print("precision: ", metrics.precision_score(test_target, test_preds2))
print("recall: ", metrics.recall_score(test_target, test_preds2))
print("f1: ", metrics.f1_score(test_target, test_preds2))
plt.figure()
colors = np.array(['b' if label == 1 else 'r' for label in http_data['attack']])
plt.scatter(http_data['dst_bytes'], http_data['src_bytes'], s=10, color=colors)
plt.show()