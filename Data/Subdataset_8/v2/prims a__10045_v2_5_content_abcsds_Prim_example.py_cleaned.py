import matplotlib.pyplot as plt
import networkx as nx
from prim import prim
graph = nx.Graph()
graph.add_edge('A', 'B', weight=3)
graph.add_edge('A', 'D', weight=5)
graph.add_edge('A', 'E', weight=9)
graph.add_edge('B', 'C', weight=5)
graph.add_edge('B', 'D', weight=4)
graph.add_edge('B', 'E', weight=8)
graph.add_edge('C', 'D', weight=7)
graph.add_edge('C', 'G', weight=3)
graph.add_edge('D', 'F', weight=8)
graph.add_edge('D', 'G', weight=5)
graph.add_edge('D', 'H', weight=6)
graph.add_edge('E', 'F', weight=2)
graph.add_edge('F', 'H', weight=10)
graph.add_edge('G', 'I', weight=1)
graph.add_edge('H', 'I', weight=3)
minimal_spanning_tree = prim(graph, 'A')
other_edges = [edge for edge in graph.edges() if edge not in minimal_spanning_tree]
print("Minimal Spanning Tree:", minimal_spanning_tree)
layout = nx.spring_layout(graph)
nx.draw_networkx_nodes(graph, layout, node_size=500)
nx.draw_networkx_edges(graph, layout, edgelist=minimal_spanning_tree, width=6)
nx.draw_networkx_edges(graph, layout, edgelist=other_edges, width=6, alpha=0.5, edge_color='b', style='dashed')
nx.draw_networkx_labels(graph, layout, font_size=20, font_family='sans-serif')
plt.axis('off')
plt.show()