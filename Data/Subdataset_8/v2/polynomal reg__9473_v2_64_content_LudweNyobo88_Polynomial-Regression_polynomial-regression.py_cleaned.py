import numpy as np
import matplotlib.pyplot as plt
from sklearn.linear_model import LinearRegression
from sklearn.preprocessing import PolynomialFeatures
X_train = np.array([[6], [8], [10], [14], [18]])
y_train = np.array([[7], [9], [13], [17.5], [18]])
x_test = np.array([[6], [8], [11], [16]])
y_test = np.array([[8], [12], [15], [18]])
linear_regressor = LinearRegression()
linear_regressor.fit(X_train, y_train)
xx_linear = np.linspace(0, 26, 100)
yy_linear = linear_regressor.predict(xx_linear.reshape(-1, 1))
plt.plot(xx_linear, yy_linear)
quadratic_featurizer = PolynomialFeatures(degree=2)
X_train_quadratic = quadratic_featurizer.fit_transform(X_train)
X_test_quadratic = quadratic_featurizer.transform(x_test)
quadratic_regressor = LinearRegression()
quadratic_regressor.fit(X_train_quadratic, y_train)
xx_quadratic = quadratic_featurizer.transform(xx_linear.reshape(-1, 1))
yy_quadratic = quadratic_regressor.predict(xx_quadratic)
plt.plot(xx_linear, yy_quadratic, c='r', linestyle='--')
plt.scatter(X_train, y_train)
plt.title('Pizza price regressed on diameter')
plt.xlabel('Diameter in inches')
plt.ylabel('Price in dollars')
plt.axis([0, 25, 0, 25])
plt.grid(True)
plt.legend(['Linear Regression', 'Quadratic Regression', 'Training Data'])
plt.show()
