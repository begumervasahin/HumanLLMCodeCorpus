
NUM_VERTICES = 20
INFINITY = 99999
def floyd_warshall(graph):
    distance = [[[0 for _ in range(NUM_VERTICES)] for _ in range(NUM_VERTICES)] for _ in range(NUM_VERTICES)]
    for i in range(NUM_VERTICES):
        for j in range(NUM_VERTICES):
            distance[i][j][0] = graph[i][j]
    for k in range(NUM_VERTICES):
        for i in range(NUM_VERTICES):
            for j in range(NUM_VERTICES):
                with_intermediate = distance[i][k][0] + distance[k][j][0]
                if with_intermediate < distance[i][j][0]:
                    distance[i][j][0] = with_intermediate
                    if distance[i][j][1] == 0:
                        distance[i][j][1] = k
                    else:
                        for n in range(NUM_VERTICES):
                            if distance[i][j][n] == 0:
                                distance[i][j][n] = k
                                break
    return distance
def print_distance_matrix(dist):
    print("\nThe following matrix shows all minimum cost paths between any two cities.\n")
    for i in range(NUM_VERTICES):
        for j in range(NUM_VERTICES):
            if dist[i][j][0] == INFINITY:
                print("%5s" % ("INF"), end='|')
            else:
                print("%5d" % (dist[i][j][0]), end='|')
            if j == NUM_VERTICES - 1:
                print("\n" + "-" * 125)
