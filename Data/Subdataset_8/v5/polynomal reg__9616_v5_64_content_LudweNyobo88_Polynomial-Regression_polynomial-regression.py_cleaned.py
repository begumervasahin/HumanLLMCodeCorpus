import numpy as np
import matplotlib.pyplot as plt
from sklearn.linear_model import LinearRegression
from sklearn.preprocessing import PolynomialFeatures
diameters_train = np.array([6, 8, 10, 14, 18]).reshape(-1, 1)
prices_train = np.array([7, 9, 13, 17.5, 18]).reshape(-1, 1)
diameters_test = np.array([6, 8, 11, 16]).reshape(-1, 1)
prices_test = np.array([8, 12, 15, 18]).reshape(-1, 1)
linear_regressor = LinearRegression()
linear_regressor.fit(diameters_train, prices_train)
diameter_range = np.linspace(0, 26, 100).reshape(-1, 1)
predicted_prices_linear = linear_regressor.predict(diameter_range)
plt.plot(diameter_range, predicted_prices_linear, label='Linear Regression')
poly_features = PolynomialFeatures(degree=2)
diameters_train_poly = poly_features.fit_transform(diameters_train)
diameters_test_poly = poly_features.transform(diameters_test)
quadratic_regressor = LinearRegression()
quadratic_regressor.fit(diameters_train_poly, prices_train)
predicted_prices_quadratic = quadratic_regressor.predict(poly_features.transform(diameter_range))
plt.plot(diameter_range, predicted_prices_quadratic, '--', color='red', label='Quadratic Regression')
plt.title('Pizza price regressed on diameter')
plt.xlabel('Diameter in inches')
plt.ylabel('Price in dollars')
plt.legend()
plt.grid(True)
plt.scatter(diameters_train, prices_train, label='Training Data')
plt.show()
print("Transformed training data with quadratic features:")
print(diameters_train_poly)
print("\nTransformed testing data with quadratic features:")
print(diameters_test_poly)