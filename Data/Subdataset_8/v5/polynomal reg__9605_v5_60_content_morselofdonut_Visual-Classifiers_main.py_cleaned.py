import numpy as np
import matplotlib.pyplot as plt
x, y = np.loadtxt('dataset.csv', delimiter=',', unpack=True)
coefficients = np.polyfit(x, y, 15)
polynomial = np.poly1d(coefficients)
distances = np.abs(y - polynomial(x))
unique_x = np.unique(x)
average_distances = np.array([[value, np.mean(distances[x == value])] for value in unique_x])
fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(18, 9))
colors_val = np.where(y > polynomial(x), 'r', 'b')
ax1.scatter(x, y, s=2, marker='o', c=colors_val)
ax1.plot(x, polynomial(x), 'k', linewidth=1)
ax1.set_title("Value Classifier")
colors_dist = np.where(distances > average_distances[:, 1][np.searchsorted(unique_x, x)], 'r', 'b')
ax2.scatter(x, y, s=2, marker='o', c=colors_dist)
ax2.plot(x, polynomial(x), 'k', linewidth=1)
ax2.set_title("Average Distance Classifier")
plt.tight_layout()
plt.show()