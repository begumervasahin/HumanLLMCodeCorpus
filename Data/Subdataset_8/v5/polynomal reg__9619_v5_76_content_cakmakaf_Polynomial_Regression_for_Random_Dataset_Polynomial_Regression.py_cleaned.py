import matplotlib.pyplot as plt
import numpy as np
from sklearn.metrics import r2_score
np.random.seed(2)
page_speeds = np.random.normal(3.0, 1.0, 100)
purchase_amount = np.random.normal(50.0, 30.0, 100) / page_speeds
plt.scatter(page_speeds, purchase_amount)
plt.xlabel("Page Speeds")
plt.ylabel("Purchase Amount")
plt.title("Page Speeds vs. Purchase Amount")
plt.show()
train_X, test_X = page_speeds[:80], page_speeds[80:]
train_Y, test_Y = purchase_amount[:80], purchase_amount[80:]
plt.scatter(train_X, train_Y, label="Training Data")
plt.scatter(test_X, test_Y, label="Testing Data")
plt.xlabel("Page Speeds")
plt.ylabel("Purchase Amount")
plt.legend()
plt.title("Training and Testing Data")
plt.show()
poly_fit = np.poly1d(np.polyfit(train_X, train_Y, 7))
x_values = np.linspace(0, 7, 100)
plt.scatter(train_X, train_Y, label="Training Data")
plt.plot(x_values, poly_fit(x_values), c='b', label="Polynomial Fit")
plt.xlabel("Page Speeds")
plt.ylabel("Purchase Amount")
plt.legend()
plt.title("Polynomial Fit on Training Data")
plt.show()
plt.scatter(test_X, test_Y, label="Testing Data")
plt.plot(x_values, poly_fit(x_values), c='b', label="Polynomial Fit")
plt.xlabel("Page Speeds")
plt.ylabel("Purchase Amount")
plt.legend()
plt.title("Polynomial Fit on Testing Data")
plt.show()
r_squared_test = r2_score(test_Y, poly_fit(test_X))
print("R-squared score for testing data:", r_squared_test)
r_squared_train = r2_score(train_Y, poly_fit(train_X))
print("R-squared score for training data:", r_squared_train)