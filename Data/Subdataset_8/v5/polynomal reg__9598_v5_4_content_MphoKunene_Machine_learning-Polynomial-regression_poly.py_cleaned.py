import numpy as np
import matplotlib.pyplot as plt
from sklearn.linear_model import LinearRegression
from sklearn.preprocessing import PolynomialFeatures
x_train = np.array([[12], [18], [20], [25], [27]])
y_train = np.array([[14], [15], [16], [20], [27]])
x_test = np.array([[12], [20], [45], [47]])
y_test = np.array([[14], [16], [50], [52]])
linear_regressor = LinearRegression()
linear_regressor.fit(x_train, y_train)
xx_linear = np.linspace(0, 28, 110).reshape(-1, 1)
yy_linear = linear_regressor.predict(xx_linear)
plt.plot(xx_linear, yy_linear, label='Linear Regression')
quadratic_featurizer = PolynomialFeatures(degree=2)
x_train_quadratic = quadratic_featurizer.fit_transform(x_train)
x_test_quadratic = quadratic_featurizer.transform(x_test)
quadratic_regressor = LinearRegression()
quadratic_regressor.fit(x_train_quadratic, y_train)
xx_quadratic = quadratic_featurizer.transform(xx_linear)
yy_quadratic = quadratic_regressor.predict(xx_quadratic)
plt.plot(xx_linear, yy_quadratic, c='r', linestyle='--', label='Quadratic Regression')
plt.scatter(x_train, y_train, label='Training Data')
plt.title('Fish Tank Price Regression based on Diameter')
plt.xlabel('Diameter (in inches)')
plt.ylabel('Price (in dollars)')
plt.xlim(0, 30)
plt.ylim(0, 30)
plt.legend()
plt.grid(True)
plt.show()
print("Training data (linear):")
print(x_train)
print("Training data (quadratic):")
print(x_train_quadratic)
print("Test data (linear):")
print(x_test)
print("Test data (quadratic):")
print(x_test_quadratic)