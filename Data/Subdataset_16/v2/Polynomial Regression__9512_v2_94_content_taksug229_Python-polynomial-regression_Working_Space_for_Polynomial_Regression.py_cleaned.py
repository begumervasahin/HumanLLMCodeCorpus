import numpy as np
import matplotlib.pyplot as plt
import pandas as pd
from sklearn.linear_model import LinearRegression
from sklearn.preprocessing import PolynomialFeatures
b1 = pd.read_csv('Position_Salaries.csv')
b2 = b1.iloc[:, 1:2].values
b3 = b1.iloc[:, 2].values
b4 = LinearRegression()
b4.fit(b2, b3)
b5 = PolynomialFeatures(degree=4)
b6 = b5.fit_transform(b2)
b7 = LinearRegression()
b7.fit(b6, b3)
plt.figure(b8 = (12, 6))
plt.subplot(1, 2, 1)
plt.scatter(b2, b3, b9 = 'red')
plt.plot(b2, b4.predict(b2), b9 = 'blue')
plt.title('Linear Regression')
plt.xlabel('Position Level')
plt.ylabel('Salary')
plt.subplot(1, 2, 2)
plt.scatter(b2, b3, b9 = 'red')
plt.plot(b2, b7.predict(b6), b9 = 'blue')
plt.title('Polynomial Regression')
plt.xlabel('Position Level')
plt.ylabel('Salary')
plt.tight_layout()
plt.show()
b10 = np.arange(min(b2), max(b2), 0.1)
b10 = b10.reshape((len(b10), 1))
plt.scatter(b2, b3, b9 = 'red')
plt.plot(b10, b7.predict(b5.transform(b10)), b9 = 'blue')
plt.title('Polynomial Regression (Smoother Curve)')
plt.xlabel('Position Level')
plt.ylabel('Salary')
plt.show()
b11 = b4.predict([[6.5]])
print(f"Linear Regression Prediction for position level 6.5: {b11[0]}")
b12 = b7.predict(b5.transform([[6.5]]))
print(f"Polynomial Regression Prediction for position level 6.5: {b12[0]}")