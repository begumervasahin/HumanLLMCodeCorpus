import numpy as np
import matplotlib.pyplot as plt
from sklearn.decomposition import PCA, KernelPCA
from sklearn.datasets import make_circles
np.random.seed(0)
X, b1 = make_circles(n_samples=400, factor=.3, noise=.05)
b2 = KernelPCA(kernel="rbf", fit_inverse_transform=True, gamma=10)
b3 = b2.fit_transform(X)
b4 = b2.inverse_transform(b3)
b5 = PCA()
b6 = b5.fit_transform(X)
plt.figure()
plt.subplot(2, 2, 1, b7 = 'equal')
plt.title("Original space")
b8 = b1 == 0
b9 = b1 == 1
plt.plot(X[b8, 0], X[b8, 1], "ro")
plt.plot(X[b9, 0], X[b9, 1], "bo")
plt.xlabel("$x_1$")
plt.ylabel("$x_2$")
X1, b10 = np.meshgrid(np.linspace(-1.5, 1.5, 50), np.linspace(-1.5, 1.5, 50))
b11 = np.array([np.ravel(X1), np.ravel(b10)]).T
b12 = b2.transform(b11)[:, 0].reshape(X1.shape)
plt.contour(X1, b10, b12, b13 = 'grey', linewidths=1, origin='lower')
plt.subplot(2, 2, 2, b7 = 'equal')
plt.plot(b6[b8, 0], b6[b8, 1], "ro")
plt.plot(b6[b9, 0], b6[b9, 1], "bo")
plt.title("Projection by PCA")
plt.xlabel("1st principal component")
plt.ylabel("2nd component")
plt.subplot(2, 2, 3, b7 = 'equal')
plt.plot(b3[b8, 0], b3[b8, 1], "ro")
plt.plot(b3[b9, 0], b3[b9, 1], "bo")
plt.title("Projection by KPCA")
plt.xlabel("1st principal component in space induced by $\phi$")
plt.ylabel("2nd component")
plt.subplot(2, 2, 4, b7 = 'equal')
plt.plot(b4[b8, 0], b4[b8, 1], "ro")
plt.plot(b4[b9, 0], b4[b9, 1], "bo")
plt.title("Original space after inverse transform")
plt.xlabel("$x_1$")
plt.ylabel("$x_2$")
plt.subplots_adjust(0.02, 0.10, 0.98, 0.94, 0.04, 0.35)
plt.show()