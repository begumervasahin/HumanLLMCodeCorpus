import numpy as np
import pandas as pd
from sklearn.model_selection import train_test_split
from sklearn import metrics, svm
from sklearn.ensemble import IsolationForest
from sklearn.neighbors import LocalOutlierFactor
b1 = pd.read_csv('kddcup.names', skiprows=1, header=None, sep=':')
b1 = dict(b1[0])
b1[41] = 'label'
b2 = list(b1.values())
b3 = pd.read_csv('kddcup.data_10_percent', low_memory=False, header=None, names=b2)
b3 = b3[(b3['service'] == "http") & (b3["logged_in"] == 1)]
b3['label'].value_counts().plot(b4 = 'bar')
b5 = ["duration", "src_bytes", "dst_bytes", "label"]
b3 = b3[b5]
b3['attack'] = np.where(b3['label'] == "normal.", 1, -1)
b6 = b3['attack']
b7 = b6[b6 == -1]
print("b7.shape:", b7.shape)
print("outlier fraction:", b7.shape[0] / b6.shape[0])
b3.drop(["label", "attack"], b8 = 1, inplace=True)
train_data, test_data, train_target, b9 = train_test_split(b3, b6, train_size=0.8)
print("Training b3 shape:", train_data.shape)
b10 = b7.shape[0] / b6.shape[0]
print("b10:", b10)
print("One-Class SVM")
b11 = svm.OneClassSVM(b10=b10, kernel='rbf', gamma=0.00005)
b11.fit(train_data)
b12 = b11.predict(train_data)
print("===================")
print("For Training Data:")
print("===================")
print("accuracy:", metrics.accuracy_score(train_target, b12))
print("precision:", metrics.precision_score(train_target, b12))
print("recall:", metrics.recall_score(train_target, b12))
print("f1:", metrics.f1_score(train_target, b12))
b13 = b11.predict(test_data)
print("===============")
print("For Test Data:")
print("===============")
print("accuracy:", metrics.accuracy_score(b9, b13))
print("precision:", metrics.precision_score(b9, b13))
print("recall:", metrics.recall_score(b9, b13))
print("f1:", metrics.f1_score(b9, b13))
print("Isolation Forest")
b14 = IsolationForest(contamination=b10, random_state=42)
b14.fit(train_data)
b15 = b14.predict(train_data)
print("===================")
print("For Training Data:")
print("===================")
print("accuracy:", metrics.accuracy_score(train_target, b15))
print("precision:", metrics.precision_score(train_target, b15))
print("recall:", metrics.recall_score(train_target, b15))
print("f1:", metrics.f1_score(train_target, b15))
b16 = b14.predict(test_data)
print("===============")
print("For Test Data:")
print("===============")
print("accuracy:", metrics.accuracy_score(b9, b16))
print("precision:", metrics.precision_score(b9, b16))
print("recall:", metrics.recall_score(b9, b16))
print("f1:", metrics.f1_score(b9, b16))
print("Local Outlier Factor")
b17 = LocalOutlierFactor(n_neighbors=35, contamination=b10)
b18 = b17.fit_predict(train_data)
print("===================")
print("For Training Data:")
print("===================")
print("accuracy:", metrics.accuracy_score(train_target, b18))
print("precision:", metrics.precision_score(train_target, b18))
print("recall:", metrics.recall_score(train_target, b18))
print("f1:", metrics.f1_score(train_target, b18))
b19 = b17.fit_predict(test_data)
print("===============")
print("For Test Data:")
print("===============")
print("accuracy:", metrics.accuracy_score(b9, b19))
print("precision:", metrics.precision_score(b9, b19))
print("recall:", metrics.recall_score(b9, b19))
print("f1:", metrics.f1_score(b9, b19))