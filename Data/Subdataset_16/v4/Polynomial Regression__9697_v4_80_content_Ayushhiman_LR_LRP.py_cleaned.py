import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.preprocessing import PolynomialFeatures
from sklearn.feature_selection import f_regression, mutual_info_regression
from sklearn.model_selection import train_test_split
from sklearn.linear_model import LinearRegression
from sklearn import metrics
b1 = pd.read_csv("Ecommerce Customers")
print(b1.head())
print(b1.describe())
sns.set_palette("GnBu_d")
sns.set_style('whitegrid')
sns.jointplot(b2 = 'Time on Website', b3='Yearly Amount Spent', data=b1)
sns.jointplot(b2 = 'Time on App', b3='Yearly Amount Spent', data=b1)
sns.jointplot(b2 = 'Time on App', b3='Length of Membership', kind='hex', data=b1)
sns.pairplot(b1)
sns.lmplot(b2 = 'Length of Membership', b3='Yearly Amount Spent', data=b1)
b3 = b1['Yearly Amount Spent']
b4 = b1[['Avg. Session Length', 'Time on App', 'Time on Website', 'Length of Membership']]
b5 = PolynomialFeatures(degree=2, interaction_only=False, include_bias=True)
b6 = b5.fit_transform(b4)
f_values, b7 = f_regression(b4, b3, center=True)
print("F-regression values:", f_values)
print("F-regression p-values:", b7)
b8 = mutual_info_regression(b4, b3, discrete_features='auto', n_neighbors=3, copy=True, random_state=None)
print("Mutual information scores:", b8)
X_train, X_test, y_train, b9 = train_test_split(b4, b3, test_size=0.3, random_state=101)
X_poly_train, b10 = train_test_split(b6, test_size=0.3, random_state=101)
b11 = b4.drop('Time on App', axis=1)
X_reduced_train, b12 = train_test_split(b11, test_size=0.3, random_state=101)
b13 = LinearRegression()
b13.fit(X_train, y_train)
b14 = LinearRegression()
b14.fit(X_reduced_train, y_train)
b15 = LinearRegression()
b15.fit(X_poly_train, y_train)
print('Model with all features Coefficients:', b13.coef_)
print('Model without "Time on App" Coefficients:', b14.coef_)
print('Polynomial Features Model Coefficients:', b15.coef_)
b16 = b13.predict(X_test)
b17 = b14.predict(b12)
b18 = b15.predict(b10)
plt.figure(b19 = (14, 6))
plt.subplot(1, 3, 1)
plt.scatter(b9, b16)
plt.xlabel('Y Test')
plt.ylabel('Predicted Y')
plt.title('All Features')
plt.subplot(1, 3, 2)
plt.scatter(b9, b17)
plt.xlabel('Y Test')
plt.ylabel('Predicted Y')
plt.title('Without "Time on App"')
plt.subplot(1, 3, 3)
plt.scatter(b9, b18)
plt.xlabel('Y Test')
plt.ylabel('Predicted Y')
plt.title('Polynomial Features')
plt.tight_layout()
plt.show()
def fonk1(model_name, b9, b16):
    print(f'{model_name} Model Performance:')
    print('MAE:', metrics.mean_absolute_error(b9, b16))
    print('MSE:', metrics.mean_squared_error(b9, b16))
    print('RMSE:', np.sqrt(metrics.mean_squared_error(b9, b16)))
    print('\n')
fonk1('All Features', b9, b16)
fonk1('Without "Time on App"', b9, b17)
fonk1('Polynomial Features', b9, b18)