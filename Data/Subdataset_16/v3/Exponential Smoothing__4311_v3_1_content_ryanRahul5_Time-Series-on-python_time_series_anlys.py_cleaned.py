def fonk2(b9, b16, order):
    b25 = ARIMA(b9, order=order)
    b26 = b25.fit(disp=-1)
    plt.figure()
    plt.plot(b16)
    plt.plot(b26.fittedvalues, b5 = 'red')
    plt.title(f'RSS: {sum((b26.fittedvalues-b16)**2):.4f}')
    plt.show()
    return b26
