import numpy as np
import matplotlib.pyplot as plt
from sklearn.decomposition import PCA, KernelPCA
from sklearn.datasets import make_circles
np.random.seed(0)
X, b1 = make_circles(n_samples=400, factor=0.3, noise=0.05)
b2 = KernelPCA(kernel="rbf", fit_inverse_transform=True, gamma=10)
b3 = b2.fit_transform(X)
b4 = b2.inverse_transform(b3)
b5 = PCA()
b6 = b5.fit_transform(X)
b7 = b1 == 0
b8 = b1 == 1
plt.figure(b9 = (12, 10))
plt.subplot(2, 2, 1, b10 = 'equal')
plt.title("Original space")
plt.plot(X[b7, 0], X[b7, 1], "ro", b11 = 'Class 0')
plt.plot(X[b8, 0], X[b8, 1], "bo", b11 = 'Class 1')
plt.xlabel("$x_1$")
plt.ylabel("$x_2$")
plt.legend()
X1, b12 = np.meshgrid(np.linspace(-1.5, 1.5, 50), np.linspace(-1.5, 1.5, 50))
b13 = np.array([X1.ravel(), b12.ravel()]).T
b14 = b2.transform(b13)[:, 0].reshape(X1.shape)
plt.contour(X1, b12, b14, b15 = 'grey', linewidths=1, origin='lower')
plt.subplot(2, 2, 2, b10 = 'equal')
plt.title("Projection by PCA")
plt.plot(b6[b7, 0], b6[b7, 1], "ro")
plt.plot(b6[b8, 0], b6[b8, 1], "bo")
plt.xlabel("1st principal component")
plt.ylabel("2nd component")
plt.subplot(2, 2, 3, b10 = 'equal')
plt.title("Projection by KPCA")
plt.plot(b3[b7, 0], b3[b7, 1], "ro")
plt.plot(b3[b8, 0], b3[b8, 1], "bo")
plt.xlabel("1st principal component in space induced by $\phi$")
plt.ylabel("2nd component")
plt.subplot(2, 2, 4, b10 = 'equal')
plt.title("Original space after inverse transform")
plt.plot(b4[b7, 0], b4[b7, 1], "ro")
plt.plot(b4[b8, 0], b4[b8, 1], "bo")
plt.xlabel("$x_1$")
plt.ylabel("$x_2$")
plt.tight_layout(b16 = 2.0)
plt.show()